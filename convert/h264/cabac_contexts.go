package h264

import "fmt"

type cabacMN struct{ m, n int8 }

// CABACModels contains all normative context slots. Ready distinguishes
// contexts initialized by the currently available table groups.
type CABACModels struct {
	Context [460]CABACContext
	Ready   [460]bool
}

type cabacBinDecoder interface {
	DecodeBin(*CABACContext) (uint8, error)
}

// InitializeEarlyCABACModels initializes ctxIdx 0..104 and the special
// terminate context 276 from H.264 Tables 9-12 through 9-18.
func InitializeEarlyCABACModels(sliceType SliceType, initIDC uint64, sliceQP int) (CABACModels, error) {
	if initIDC > 2 {
		return CABACModels{}, fmt.Errorf("invalid cabac_init_idc %d", initIDC)
	}
	var result CABACModels
	set := func(first int, values []cabacMN) {
		for index, value := range values {
			result.Context[first+index] = NewCABACContext(value.m, value.n, sliceQP)
			result.Ready[first+index] = true
		}
	}
	set(0, cabacInit0To10[:])
	if sliceType != SliceI && sliceType != SliceSI {
		set(11, cabacInit11To23[initIDC][:])
		set(24, cabacInit24To39[initIDC][:])
		set(40, cabacInit40To53[initIDC][:])
		set(54, cabacInit54To59[initIDC][:])
	}
	set(60, cabacInit60To69[:])
	column := int(initIDC) + 1
	if sliceType == SliceI || sliceType == SliceSI {
		column = 0
	}
	for index := range cabacInit70To104 {
		value := cabacInit70To104[index][column]
		set(70+index, []cabacMN{value})
	}
	if sliceType == SliceI || sliceType == SliceSI {
		set(105, cabacInitI105To165[:])
		set(166, cabacInitI166To226[:])
		set(227, cabacInitI227To275[:])
	} else if initIDC == 0 {
		set(105, cabacInitInter0_105To275[:])
	} else if initIDC == 1 {
		set(105, cabacInitInter1_105To275[:])
	} else {
		set(105, cabacInitInter2_105To275[:])
	}
	result.Context[276], result.Ready[276] = CABACContext{State: 63}, true
	return result, nil
}

func (m *CABACModels) Decode(decoder cabacBinDecoder, index int) (uint8, error) {
	if m == nil || index < 0 || index >= len(m.Context) || !m.Ready[index] {
		return 0, fmt.Errorf("CABAC context %d is not initialized", index)
	}
	if decoder == nil {
		return 0, fmt.Errorf("nil CABAC bin decoder")
	}
	return decoder.DecodeBin(&m.Context[index])
}

